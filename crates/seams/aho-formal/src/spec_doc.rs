//! `14` — the System Spec: one literate `spec/SPEC.md`.
//!
//! Sections are level-2 headings `## <n> <Title>` in the fixed order 1–10. Formal blocks are
//! fenced blocks whose info string names a language and the invariant(s) they formalize:
//! ```` ```tla id=inv.log.append-only ````, ```` ```cfg id=inv.log.append-only ```` (the TLC
//! model for that id's module), ```` ```lean id=inv.order.total module=Spec.Order ````.
//! §6 claims are `### <id>` headings followed by `- key: value` fields (`statement`, `kind`,
//! `covers`, `mode`, `actions`, `owner`, `rationale`, `supersedes`).
//!
//! `extract` writes `tla/*.tla`, `tla/*.cfg`, `lean/**/*.lean` (never edited by hand; each
//! starts with a marker line), `freshness` compares them, and `render_generated` rewrites §9
//! Coverage and §10 History from the log — the agent never writes those two.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt;
use std::path::{Path, PathBuf};

use aho_log::{CheckMode, Entry, EntryKind, FormalKind, State, Verdict};
use aho_types::{EntryId, Hash};
use serde::Serialize;

use crate::tla;

/// Marker on the first line of every extracted file; `freshness`/`extract` only ever touch
/// files that carry it.
pub const EXTRACT_MARKER: &str = "Extracted from SPEC.md by aho";
pub const GENERATED_NOTE: &str = "<!-- generated by aho from the session log (`aho spec render`); edits here are overwritten -->";

#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize)]
pub enum SpecSection {
    Purpose,
    Vocabulary,
    Structure,
    State,
    Actions,
    Invariants,
    Assumptions,
    Refinements,
    Coverage,
    History,
}

impl SpecSection {
    pub const ALL: [SpecSection; 10] = [
        SpecSection::Purpose,
        SpecSection::Vocabulary,
        SpecSection::Structure,
        SpecSection::State,
        SpecSection::Actions,
        SpecSection::Invariants,
        SpecSection::Assumptions,
        SpecSection::Refinements,
        SpecSection::Coverage,
        SpecSection::History,
    ];
    pub fn number(self) -> u8 {
        SpecSection::ALL.iter().position(|s| *s == self).map(|i| i as u8 + 1).unwrap_or(0)
    }
    pub fn title(self) -> &'static str {
        match self {
            SpecSection::Purpose => "Purpose",
            SpecSection::Vocabulary => "Vocabulary",
            SpecSection::Structure => "Structure",
            SpecSection::State => "State",
            SpecSection::Actions => "Actions",
            SpecSection::Invariants => "Invariants",
            SpecSection::Assumptions => "Assumptions",
            SpecSection::Refinements => "Refinements",
            SpecSection::Coverage => "Coverage",
            SpecSection::History => "History",
        }
    }
    /// §9 and §10 are folds of the log; nobody writes them by hand.
    pub fn generated(self) -> bool {
        matches!(self, SpecSection::Coverage | SpecSection::History)
    }
    pub fn heading(self) -> String {
        format!("## {} {}", self.number(), self.title())
    }
    /// `1 Purpose`, `1. Purpose`, `Purpose`, `9 Coverage (generated)` → the section.
    pub fn parse_heading(text: &str) -> Option<SpecSection> {
        let t = text.trim();
        let (num, rest) = match t.find(|c: char| !c.is_ascii_digit()) {
            Some(0) => (None, t),
            Some(i) => (t[..i].parse::<u8>().ok(), t[i..].trim_start_matches(['.', ')']).trim()),
            None => (t.parse::<u8>().ok(), ""),
        };
        let word: String = rest.chars().take_while(|c| c.is_alphabetic()).collect();
        let by_title = SpecSection::ALL.into_iter().find(|s| s.title().eq_ignore_ascii_case(&word));
        match (num, by_title) {
            (Some(n), Some(s)) if s.number() == n => Some(s),
            (Some(_), Some(_)) => None,
            (None, s) => s,
            (Some(n), None) if word.is_empty() => SpecSection::ALL.get(usize::from(n).wrapping_sub(1)).copied(),
            _ => None,
        }
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Serialize)]
pub enum BlockLang {
    Tla,
    /// TLC model configuration for the module of the same id.
    Cfg,
    Lean,
}

#[derive(Clone, Debug, PartialEq, Eq, Serialize)]
pub struct Block {
    pub lang: BlockLang,
    /// Invariant ids this block formalizes (`id=a,b`).
    pub ids: Vec<String>,
    /// `module=` attribute (Lean; optional for TLA+, which names itself).
    pub module: Option<String>,
    pub body: String,
    /// 1-based line of the opening fence.
    pub line: usize,
    pub section: Option<SpecSection>,
}

impl Block {
    pub fn kind(&self) -> FormalKind {
        match self.lang {
            BlockLang::Lean => FormalKind::Lean,
            BlockLang::Tla | BlockLang::Cfg => FormalKind::Tla,
        }
    }
}

#[derive(Clone, Debug, PartialEq, Eq, Serialize)]
pub struct Claim {
    pub id: String,
    pub line: usize,
    pub fields: BTreeMap<String, String>,
    /// Everything under the heading that is not a field or a fenced block.
    pub prose: String,
}

impl Claim {
    pub fn field(&self, k: &str) -> Option<&str> {
        self.fields.get(k).map(String::as_str).filter(|v| !v.is_empty())
    }
    pub fn statement(&self) -> &str {
        self.field("statement").unwrap_or("")
    }
    /// safety | liveness | refinement | functional
    pub fn class(&self) -> &str {
        self.field("kind").unwrap_or("safety")
    }
    pub fn covers(&self) -> Vec<String> {
        list(self.field("covers"))
    }
    pub fn actions(&self) -> Vec<String> {
        list(self.field("actions"))
    }
    pub fn mode(&self) -> Option<CheckMode> {
        parse_mode(self.field("mode")?)
    }
    /// `supersedes: inv.old — why` → `("inv.old", "why")`.
    pub fn supersedes(&self) -> Option<(String, String)> {
        let v = self.field("supersedes")?;
        let v = v.trim().trim_matches('`');
        let id: String = v.chars().take_while(|c| !c.is_whitespace() && *c != ':' && *c != '`' && *c != ',').collect();
        if id.is_empty() {
            return None;
        }
        let rest = v[id.len()..].trim_start_matches(['`', ' ', ':', ',', '—', '-', '(']).trim_end_matches(')').trim();
        let why = if rest.is_empty() { self.field("why").unwrap_or("").to_string() } else { rest.to_string() };
        Some((id, why))
    }
}

fn list(v: Option<&str>) -> Vec<String> {
    v.map(|s| s.split(',').map(|x| x.trim().trim_matches('`').to_string()).filter(|x| !x.is_empty()).collect()).unwrap_or_default()
}

/// `bounded(4)` / `Bounded 4` / `inductive` / `proof` / `trace`.
pub fn parse_mode(s: &str) -> Option<CheckMode> {
    let t = s.trim().to_ascii_lowercase();
    let digits: String = t.chars().filter(|c| c.is_ascii_digit()).collect();
    if t.starts_with("bounded") {
        return Some(CheckMode::Bounded(digits.parse().unwrap_or(0)));
    }
    match t.as_str() {
        "inductive" => Some(CheckMode::Inductive),
        "proof" => Some(CheckMode::Proof),
        "trace" => Some(CheckMode::Trace),
        _ => None,
    }
}

#[derive(Clone, Debug, PartialEq, Eq, Serialize)]
pub struct Section {
    pub which: SpecSection,
    pub heading: String,
    /// 1-based line of the heading; the section runs to the next level-2 heading.
    pub line: usize,
    pub end_line: usize,
    pub body: String,
}

#[derive(Clone, Debug, PartialEq, Eq, Serialize)]
pub struct SpecDoc {
    pub title: String,
    pub sections: Vec<Section>,
    pub blocks: Vec<Block>,
    pub claims: Vec<Claim>,
    /// §5 action names (`### Name` headings or `- **Name**` bullets).
    pub actions: Vec<String>,
    pub source: String,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub enum SpecError {
    UnknownSection { line: usize, heading: String },
    DuplicateSection { line: usize, section: SpecSection },
    OutOfOrder { line: usize, section: SpecSection, after: SpecSection },
    UnterminatedFence { line: usize },
    BlockWithoutId { line: usize },
    DuplicateClaim { line: usize, id: String },
    ClaimOutsideInvariants { line: usize, section: String },
}

impl fmt::Display for SpecError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            SpecError::UnknownSection { line, heading } => write!(
                f,
                "SPEC.md:{line}: `## {heading}` is not one of the ten sections (1 Purpose … 10 History); rename it or make it a `###` subsection"
            ),
            SpecError::DuplicateSection { line, section } => {
                write!(f, "SPEC.md:{line}: section {} {} appears twice; merge the two", section.number(), section.title())
            }
            SpecError::OutOfOrder { line, section, after } => write!(
                f,
                "SPEC.md:{line}: section {} {} comes after {} {}; sections run 1 to 10 in order",
                section.number(),
                section.title(),
                after.number(),
                after.title()
            ),
            SpecError::UnterminatedFence { line } => write!(f, "SPEC.md:{line}: this fenced block is never closed"),
            SpecError::BlockWithoutId { line } => {
                write!(f, "SPEC.md:{line}: a formal block needs the invariant it formalizes, e.g. ```tla id=inv.log.append-only")
            }
            SpecError::DuplicateClaim { line, id } => {
                write!(f, "SPEC.md:{line}: invariant `{id}` is stated twice; a changed statement is a new id with `supersedes: {id}`")
            }
            SpecError::ClaimOutsideInvariants { line, section } => {
                write!(
                    f,
                    "SPEC.md:{line}: a `statement:` field sits under `## {section}`; claims live in §6 Invariants as `### <id>` entries"
                )
            }
        }
    }
}

impl std::error::Error for SpecError {}

struct Fence {
    ch: char,
    len: usize,
    line: usize,
    info: String,
    body: Vec<String>,
}

fn fence_open(l: &str) -> Option<(char, usize, String)> {
    let t = l.trim_start();
    let ch = t.chars().next()?;
    if ch != '`' && ch != '~' {
        return None;
    }
    let len = t.chars().take_while(|c| *c == ch).count();
    (len >= 3).then(|| (ch, len, t[len..].trim().to_string()))
}

fn parse_info(info: &str) -> (String, BTreeMap<String, String>) {
    let mut parts = info.split_whitespace();
    let lang = parts.next().unwrap_or("").to_ascii_lowercase();
    let attrs = parts.filter_map(|p| p.split_once('=')).map(|(k, v)| (k.to_ascii_lowercase(), v.trim_matches('"').to_string())).collect();
    (lang, attrs)
}

fn heading(l: &str, level: usize) -> Option<&str> {
    let hashes = "#".repeat(level);
    let rest = l.strip_prefix(&hashes)?;
    rest.strip_prefix(' ').map(str::trim).filter(|_| !rest.starts_with('#'))
}

fn field_line(l: &str) -> Option<(String, String)> {
    let t = l.trim_start().strip_prefix("- ").or_else(|| l.trim_start().strip_prefix("* "))?;
    let (k, v) = t.split_once(':')?;
    let k = k.trim().trim_matches('*').trim().to_ascii_lowercase();
    (!k.is_empty() && k.chars().all(|c| c.is_ascii_alphabetic() || c == '_' || c == ' '))
        .then(|| (k.replace(' ', "_"), v.trim().to_string()))
}

fn claim_id(h: &str) -> String {
    h.split_whitespace().next().unwrap_or("").trim_matches('`').to_string()
}

impl SpecDoc {
    pub fn parse(text: &str) -> Result<SpecDoc, SpecError> {
        let lines: Vec<&str> = text.lines().collect();
        let mut title = String::new();
        let mut sections: Vec<Section> = Vec::new();
        let mut blocks = Vec::new();
        let mut claims: Vec<Claim> = Vec::new();
        let mut actions = Vec::new();
        let mut current: Option<SpecSection> = None;
        let mut claim: Option<Claim> = None;
        let mut fence: Option<Fence> = None;
        let mut body: Vec<&str> = Vec::new();

        let close_section = |sections: &mut Vec<Section>, body: &mut Vec<&str>, end: usize| {
            if let Some(s) = sections.last_mut() {
                s.body = body.join("\n");
                s.end_line = end;
            }
            body.clear();
        };
        let close_claim = |claims: &mut Vec<Claim>, claim: &mut Option<Claim>| -> Result<(), SpecError> {
            if let Some(c) = claim.take() {
                if claims.iter().any(|x| x.id == c.id) {
                    return Err(SpecError::DuplicateClaim { line: c.line, id: c.id });
                }
                claims.push(c);
            }
            Ok(())
        };

        for (i, l) in lines.iter().enumerate() {
            let n = i + 1;
            if let Some(f) = fence.as_mut() {
                let t = l.trim_start();
                if t.starts_with(&f.ch.to_string().repeat(f.len)) && t.trim_matches(f.ch).trim().is_empty() {
                    let Some(f) = fence.take() else { continue };
                    let (lang, attrs) = parse_info(&f.info);
                    let lang = match lang.as_str() {
                        "tla" | "tla+" | "tlaplus" => Some(BlockLang::Tla),
                        "cfg" | "tlc" | "tla-cfg" => Some(BlockLang::Cfg),
                        "lean" | "lean4" => Some(BlockLang::Lean),
                        _ => None,
                    };
                    if let Some(lang) = lang {
                        let ids = list(attrs.get("id").map(String::as_str));
                        if ids.is_empty() {
                            return Err(SpecError::BlockWithoutId { line: f.line });
                        }
                        let mut b = f.body.join("\n");
                        b.push('\n');
                        blocks.push(Block { lang, ids, module: attrs.get("module").cloned(), body: b, line: f.line, section: current });
                    }
                } else {
                    f.body.push(l.to_string());
                }
                body.push(l);
                continue;
            }
            if let Some((ch, len, info)) = fence_open(l) {
                fence = Some(Fence { ch, len, line: n, info, body: Vec::new() });
                body.push(l);
                continue;
            }
            if let Some(t) = heading(l, 1) {
                if title.is_empty() {
                    title = t.to_string();
                }
                continue;
            }
            if let Some(h) = heading(l, 2) {
                close_claim(&mut claims, &mut claim)?;
                close_section(&mut sections, &mut body, n - 1);
                let which = SpecSection::parse_heading(h).ok_or_else(|| SpecError::UnknownSection { line: n, heading: h.to_string() })?;
                if sections.iter().any(|s| s.which == which) {
                    return Err(SpecError::DuplicateSection { line: n, section: which });
                }
                if let Some(prev) = current.filter(|p| *p > which) {
                    return Err(SpecError::OutOfOrder { line: n, section: which, after: prev });
                }
                current = Some(which);
                sections.push(Section { which, heading: h.to_string(), line: n, end_line: lines.len(), body: String::new() });
                continue;
            }
            body.push(l);
            if let Some(h) = heading(l, 3) {
                close_claim(&mut claims, &mut claim)?;
                match current {
                    Some(SpecSection::Invariants) => {
                        claim = Some(Claim { id: claim_id(h), line: n, fields: BTreeMap::new(), prose: String::new() });
                    }
                    Some(SpecSection::Actions) => actions.push(claim_id(h)),
                    _ => {}
                }
                continue;
            }
            if current == Some(SpecSection::Actions) {
                let t = l.trim_start();
                if let Some(rest) = t.strip_prefix("- **").or_else(|| t.strip_prefix("* **"))
                    && let Some(name) = rest.split("**").next().filter(|s| !s.is_empty())
                {
                    actions.push(name.trim().to_string());
                }
            }
            if let Some(c) = claim.as_mut() {
                match field_line(l) {
                    Some((k, v)) => {
                        c.fields.insert(k, v);
                    }
                    None if !l.trim().is_empty() => {
                        c.prose.push_str(l.trim());
                        c.prose.push('\n');
                    }
                    None => {}
                }
            } else if current != Some(SpecSection::Invariants)
                && heading(l, 3).is_none()
                && field_line(l).is_some_and(|(k, _)| k == "statement")
            {
                let section = sections.last().map(|s| s.heading.clone()).unwrap_or_default();
                return Err(SpecError::ClaimOutsideInvariants { line: n, section });
            }
        }
        if let Some(f) = fence {
            return Err(SpecError::UnterminatedFence { line: f.line });
        }
        close_claim(&mut claims, &mut claim)?;
        close_section(&mut sections, &mut body, lines.len());
        Ok(SpecDoc { title, sections, blocks, claims, actions, source: text.to_string() })
    }

    pub fn section(&self, s: SpecSection) -> Option<&Section> {
        self.sections.iter().find(|x| x.which == s)
    }
    pub fn claim(&self, id: &str) -> Option<&Claim> {
        self.claims.iter().find(|c| c.id == id)
    }
    pub fn blocks_for<'a>(&'a self, id: &'a str) -> impl Iterator<Item = &'a Block> + 'a {
        self.blocks.iter().filter(move |b| b.ids.iter().any(|x| x == id))
    }
    /// Ids that have at least one formal block.
    pub fn formalized(&self) -> BTreeSet<&str> {
        self.blocks.iter().filter(|b| b.lang != BlockLang::Cfg).flat_map(|b| b.ids.iter().map(String::as_str)).collect()
    }
    /// Hash of every formal block that formalizes `id` (language, module, text) in document
    /// order: identifies what a check of `id` checks. Freshness is judged against the workspace
    /// checkpoint (13), which covers edits to this document too.
    pub fn formal_hash(&self, id: &str) -> Option<Hash> {
        let parts: Vec<(BlockLang, &Option<String>, &str)> = self.blocks_for(id).map(|b| (b.lang, &b.module, b.body.as_str())).collect();
        (!parts.is_empty()).then(|| Hash::of_json(&parts))
    }

    /// The TLA+ module a block (or the id's TLA+ block) lives in.
    pub fn tla_module_of(&self, id: &str) -> Option<String> {
        self.blocks_for(id).find(|b| b.lang == BlockLang::Tla).and_then(|b| b.module.clone().or_else(|| tla::module_name(&b.body)))
    }

    /// Every file `extract` writes, relative to the output dir, with its exact content.
    pub fn extracts(&self) -> Result<Vec<(PathBuf, String)>, ExtractError> {
        let mut tla_files: BTreeMap<String, (usize, String)> = BTreeMap::new();
        let mut cfg_files: BTreeMap<String, (usize, String)> = BTreeMap::new();
        let mut lean_files: BTreeMap<String, String> = BTreeMap::new();
        for b in &self.blocks {
            match b.lang {
                BlockLang::Tla => {
                    let name = tla::module_name(&b.body).ok_or(ExtractError::NoModuleHeader { line: b.line })?;
                    if let Some(m) = &b.module
                        && *m != name
                    {
                        return Err(ExtractError::ModuleMismatch { line: b.line, attr: m.clone(), header: name });
                    }
                    if let Some((first, _)) = tla_files.get(&name) {
                        return Err(ExtractError::DuplicateModule { line: b.line, module: name, first: *first });
                    }
                    tla_files.insert(name, (b.line, b.body.clone()));
                }
                BlockLang::Cfg => {
                    let module = match &b.module {
                        Some(m) => m.clone(),
                        None => b
                            .ids
                            .iter()
                            .find_map(|id| self.tla_module_of(id))
                            .ok_or_else(|| ExtractError::CfgWithoutModule { line: b.line, id: b.ids.join(",") })?,
                    };
                    if let Some((first, _)) = cfg_files.get(&module) {
                        return Err(ExtractError::DuplicateModule { line: b.line, module: format!("{module}.cfg"), first: *first });
                    }
                    cfg_files.insert(module, (b.line, b.body.clone()));
                }
                BlockLang::Lean => {
                    let module = b.module.clone().unwrap_or_else(|| lean_module_for(b.ids.first().map(String::as_str).unwrap_or("spec")));
                    let text = lean_files.entry(module).or_default();
                    if !text.is_empty() {
                        text.push('\n');
                    }
                    text.push_str(&b.body);
                }
            }
        }
        let mut out = Vec::new();
        for (m, (_, body)) in tla_files {
            out.push((
                PathBuf::from("tla").join(format!("{m}.tla")),
                format!("\\* {EXTRACT_MARKER}; edit SPEC.md, not this file.\n{body}"),
            ));
        }
        for (m, (_, body)) in cfg_files {
            out.push((
                PathBuf::from("tla").join(format!("{m}.cfg")),
                format!("\\* {EXTRACT_MARKER}; edit SPEC.md, not this file.\n{body}"),
            ));
        }
        for (m, body) in lean_files {
            let mut p = PathBuf::from("lean");
            for part in m.split('.') {
                p.push(part);
            }
            p.set_extension("lean");
            out.push((p, format!("-- {EXTRACT_MARKER}; edit SPEC.md, not this file.\n{body}")));
        }
        Ok(out)
    }
}

/// `inv.order.total` → `InvOrderTotal` (the default Lean module for a block without `module=`).
pub fn lean_module_for(id: &str) -> String {
    id.split(|c: char| !c.is_ascii_alphanumeric())
        .filter(|p| !p.is_empty())
        .map(|p| {
            let mut cs = p.chars();
            cs.next().map(|c| c.to_ascii_uppercase().to_string() + cs.as_str()).unwrap_or_default()
        })
        .collect()
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub enum ExtractError {
    NoModuleHeader { line: usize },
    ModuleMismatch { line: usize, attr: String, header: String },
    DuplicateModule { line: usize, module: String, first: usize },
    CfgWithoutModule { line: usize, id: String },
    Io(String),
}

impl fmt::Display for ExtractError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            ExtractError::NoModuleHeader { line } => {
                write!(f, "SPEC.md:{line}: a tla block must be a whole module starting with `---- MODULE Name ----`; nothing was extracted")
            }
            ExtractError::ModuleMismatch { line, attr, header } => {
                write!(f, "SPEC.md:{line}: module={attr} but the block declares MODULE {header}; make them agree")
            }
            ExtractError::DuplicateModule { line, module, first } => {
                write!(
                    f,
                    "SPEC.md:{line}: `{module}` is already defined at line {first}; one block per module (list several ids with id=a,b)"
                )
            }
            ExtractError::CfgWithoutModule { line, id } => {
                write!(f, "SPEC.md:{line}: this cfg block is for `{id}`, which has no tla block; add one or set module=")
            }
            ExtractError::Io(e) => write!(f, "{e}"),
        }
    }
}

impl std::error::Error for ExtractError {}

#[derive(Clone, Debug, Default, PartialEq, Eq, Serialize)]
pub struct ExtractReport {
    pub written: Vec<PathBuf>,
    /// Extracted files (they carry the marker) the document no longer produces.
    pub removed: Vec<PathBuf>,
}

/// Writes every extract under `out_dir` (normally `spec/`) and removes marker-carrying files the
/// document no longer produces. Files without the marker are never touched.
#[allow(clippy::disallowed_methods, reason = "authority: formal-extract-write")]
pub fn extract(doc: &SpecDoc, out_dir: &Path) -> Result<ExtractReport, ExtractError> {
    let files = doc.extracts()?;
    let io =
        |p: &Path, e: std::io::Error| ExtractError::Io(format!("could not write {}: {e}; nothing after it was extracted", p.display()));
    let mut report = ExtractReport::default();
    for (rel, text) in &files {
        let p = out_dir.join(rel);
        if let Some(dir) = p.parent() {
            std::fs::create_dir_all(dir).map_err(|e| io(dir, e))?;
        }
        if std::fs::read_to_string(&p).ok().as_deref() != Some(text.as_str()) {
            std::fs::write(&p, text).map_err(|e| io(&p, e))?;
        }
        report.written.push(p);
    }
    let expected: BTreeSet<PathBuf> = files.iter().map(|(r, _)| out_dir.join(r)).collect();
    for p in marked_files(out_dir) {
        if !expected.contains(&p) {
            std::fs::remove_file(&p).map_err(|e| ExtractError::Io(format!("could not remove stale extract {}: {e}", p.display())))?;
            report.removed.push(p);
        }
    }
    Ok(report)
}

/// Extract-marked files currently under `out_dir/tla` and `out_dir/lean`.
#[allow(clippy::disallowed_methods, reason = "authority: formal-extract-scan")]
fn marked_files(out_dir: &Path) -> Vec<PathBuf> {
    fn walk(dir: &Path, out: &mut Vec<PathBuf>) {
        let Ok(rd) = std::fs::read_dir(dir) else { return };
        let mut entries: Vec<PathBuf> = rd.filter_map(|e| e.ok().map(|e| e.path())).collect();
        entries.sort();
        for p in entries {
            if p.is_dir() {
                walk(&p, out);
            } else if matches!(p.extension().and_then(|e| e.to_str()), Some("tla" | "cfg" | "lean")) {
                let first = std::fs::read_to_string(&p).ok().and_then(|t| t.lines().next().map(str::to_string)).unwrap_or_default();
                if first.contains(EXTRACT_MARKER) {
                    out.push(p);
                }
            }
        }
    }
    let mut out = Vec::new();
    walk(&out_dir.join("tla"), &mut out);
    walk(&out_dir.join("lean"), &mut out);
    out
}

#[derive(Clone, Debug, Default, PartialEq, Eq, Serialize)]
pub struct Freshness {
    /// On disk but different from what SPEC.md produces (hand-edited, or SPEC.md changed).
    pub stale: Vec<PathBuf>,
    pub missing: Vec<PathBuf>,
    /// Extract-marked files SPEC.md no longer produces.
    pub orphaned: Vec<PathBuf>,
}

impl Freshness {
    pub fn is_fresh(&self) -> bool {
        self.stale.is_empty() && self.missing.is_empty() && self.orphaned.is_empty()
    }
    /// Operator-facing summary for a failing gate.
    pub fn describe(&self) -> String {
        if self.is_fresh() {
            return "spec extracts are fresh".into();
        }
        let show = |v: &[PathBuf]| v.iter().map(|p| p.display().to_string()).collect::<Vec<_>>().join(", ");
        let mut parts = Vec::new();
        if !self.stale.is_empty() {
            parts.push(format!("differ from SPEC.md: {}", show(&self.stale)));
        }
        if !self.missing.is_empty() {
            parts.push(format!("missing: {}", show(&self.missing)));
        }
        if !self.orphaned.is_empty() {
            parts.push(format!("no longer in SPEC.md: {}", show(&self.orphaned)));
        }
        format!("spec extracts are out of date ({}); run `aho spec render` to regenerate them from SPEC.md", parts.join("; "))
    }
}

/// The freshness gate: extracts on disk equal what `doc` produces, byte for byte.
#[allow(clippy::disallowed_methods, reason = "authority: formal-extract-freshness")]
pub fn freshness(doc: &SpecDoc, out_dir: &Path) -> Result<Freshness, ExtractError> {
    let files = doc.extracts()?;
    let mut f = Freshness::default();
    let expected: BTreeSet<PathBuf> = files.iter().map(|(r, _)| out_dir.join(r)).collect();
    for (rel, text) in &files {
        let p = out_dir.join(rel);
        match std::fs::read_to_string(&p) {
            Ok(t) if t == *text => {}
            Ok(_) => f.stale.push(p),
            Err(_) => f.missing.push(p),
        }
    }
    f.orphaned = marked_files(out_dir).into_iter().filter(|p| !expected.contains(p)).collect();
    Ok(f)
}

