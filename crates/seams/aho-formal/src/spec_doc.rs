/// What the log says about one invariant.
#[derive(Clone, Debug, Default, PartialEq)]
pub struct InvariantRecord {
    /// Every `InvariantRegistered` for this id: `(entry, kind, statement, covers)`.
    pub registrations: Vec<(EntryId, FormalKind, String, Vec<String>)>,
    /// Latest `InvariantChecked`: `(mode, verdict, code_hash)`.
    pub checked: Option<(Option<CheckMode>, Verdict, Hash)>,
    /// `InvariantMutated` since the latest check of the current code hash: `(mutant, caught)`.
    pub mutants: Vec<(String, bool)>,
}

/// The formal projection §9/§10 are rendered from.
#[derive(Clone, Debug, Default, PartialEq)]
pub struct Ledger {
    pub invariants: BTreeMap<String, InvariantRecord>,
    /// Built from entries, so an empty `mutants` means "never mutated" rather than "not in the fold".
    pub mutants_known: bool,
    /// The tree of the latest `Workspace/Checkpoint`: the code every verdict is judged against
    /// (13). `None` before the first checkpoint, when the recorded verdicts stand.
    pub code: Option<Hash>,
}

impl Ledger {
    /// Verdicts only (`State::invariants`): vacuity is visible when the log recorded a
    /// `Vacuous` verdict; mutants and registrations are not in the fold.
    pub fn from_state(state: &State) -> Ledger {
        let invariants = state
            .invariants
            .iter()
            .map(|(id, (v, h))| (id.clone(), InvariantRecord { checked: Some((None, v.clone(), *h)), ..Default::default() }))
            .collect();
        Ledger { invariants, mutants_known: false, code: state.checkpoints.last().map(|c| c.1) }
    }

    /// The full projection from the branch: registrations (goalpost moves), verdicts, mutants.
    /// Mutants recorded before a check of a different code hash no longer count.
    pub fn from_entries(entries: &[Entry]) -> Ledger {
        let mut l = Ledger { mutants_known: true, ..Ledger::default() };
        for e in entries {
            match &e.kind {
                EntryKind::InvariantRegistered { id, kind, statement, covers } => {
                    l.invariants.entry(id.clone()).or_default().registrations.push((e.id, *kind, statement.clone(), covers.clone()));
                }
                EntryKind::InvariantChecked { id, mode, verdict, code_hash } => {
                    let r = l.invariants.entry(id.clone()).or_default();
                    if r.checked.as_ref().map(|c| c.2) != Some(*code_hash) {
                        r.mutants.clear();
                    }
                    r.checked = Some((Some(*mode), verdict.clone(), *code_hash));
                }
                EntryKind::InvariantMutated { id, mutant, caught } => {
                    l.invariants.entry(id.clone()).or_default().mutants.push((mutant.clone(), *caught));
                }
                EntryKind::WorkspaceCheckpoint { tree, .. } => l.code = Some(*tree),
                _ => {}
            }
        }
        l
    }
}

/// Status of one invariant as the document shows it.
#[derive(Clone, Debug, PartialEq, Eq, PartialOrd, Ord, Serialize)]
pub enum Status {
    Pass,
    Fail,
    Unknown,
    Stale,
    Vacuous,
    Draft,
}

impl Status {
    pub fn glyph(&self) -> &'static str {
        match self {
            Status::Pass => "● Pass",
            Status::Fail => "✕ Fail",
            Status::Unknown => "? Unknown",
            Status::Stale => "◌ Stale",
            Status::Vacuous => "⚠ Vacuous",
            Status::Draft => "○ Draft",
        }
    }
}

/// Doc 14 status of `id`: Draft without a formal block or a verdict; Stale when the workspace
/// (this document included) moved past the code the verdict was checked against (13,
/// [`Ledger::code`]); Vacuous when mutants were tried and none was caught (or the log says so);
/// otherwise the verdict.
pub fn status(doc: &SpecDoc, ledger: &Ledger, id: &str) -> Status {
    if doc.formal_hash(id).is_none() {
        return Status::Draft;
    }
    let Some(rec) = ledger.invariants.get(id) else { return Status::Draft };
    let Some((_, verdict, hash)) = &rec.checked else {
        return if !rec.mutants.is_empty() && rec.mutants.iter().all(|(_, c)| !c) { Status::Vacuous } else { Status::Draft };
    };
    if matches!(verdict, Verdict::Stale) || ledger.code.is_some_and(|c| c != *hash) {
        return Status::Stale;
    }
    if matches!(verdict, Verdict::Vacuous) || (!rec.mutants.is_empty() && rec.mutants.iter().all(|(_, c)| !c)) {
        return Status::Vacuous;
    }
    match verdict {
        Verdict::Pass => Status::Pass,
        Verdict::Fail { .. } => Status::Fail,
        Verdict::Unknown { .. } => Status::Unknown,
        Verdict::Stale => Status::Stale,
        Verdict::Vacuous => Status::Vacuous,
    }
}

/// §9 + §10 from the log's verdicts (`State::invariants`). See [`render_ledger`] for the
/// full projection (goalpost moves, mutants) built from the entries.
pub fn render_generated(doc: &SpecDoc, state: &State) -> String {
    render_ledger(doc, &Ledger::from_state(state))
}

/// The document with §9 Coverage and §10 History regenerated (appended when absent). Every
/// other byte of the source is kept.
pub fn render_ledger(doc: &SpecDoc, ledger: &Ledger) -> String {
    let lines: Vec<&str> = doc.source.lines().collect();
    let cut = doc.section(SpecSection::Coverage).or_else(|| doc.section(SpecSection::History)).map(|s| s.line - 1).unwrap_or(lines.len());
    let mut out = lines[..cut].join("\n");
    while out.ends_with("\n\n") || out.ends_with(' ') {
        out.pop();
    }
    if !out.is_empty() && !out.ends_with('\n') {
        out.push('\n');
    }
    if !out.is_empty() {
        out.push('\n');
    }
    out.push_str(&coverage(doc, ledger));
    out.push('\n');
    out.push_str(&history(doc, ledger));
    out
}

fn coverage(doc: &SpecDoc, ledger: &Ledger) -> String {
    let mut s = format!("{}\n\n{GENERATED_NOTE}\n\n", SpecSection::Coverage.heading());
    let formalized = doc.formalized();
    s.push_str("| invariant | kind | formal | status | mutants caught |\n|---|---|---|---|---|\n");
    for c in &doc.claims {
        let kinds: BTreeSet<&str> =
            doc.blocks_for(&c.id).filter(|b| b.lang != BlockLang::Cfg).map(|b| crate::kind_name(b.kind())).collect();
        let formal = if kinds.is_empty() { "—".to_string() } else { kinds.into_iter().collect::<Vec<_>>().join(", ") };
        let st = status(doc, ledger, &c.id);
        let caught = ledger
            .invariants
            .get(&c.id)
            .filter(|r| !r.mutants.is_empty())
            .map(|r| format!("{}/{}", r.mutants.iter().filter(|m| m.1).count(), r.mutants.len()))
            .unwrap_or_else(|| "—".into());
        s.push_str(&format!("| `{}` | {} | {} | {} | {} |\n", c.id, c.class(), formal, st.glyph(), caught));
    }
    let bullets = |title: &str, items: Vec<String>, s: &mut String| {
        s.push_str(&format!("\n**{title}** "));
        if items.is_empty() {
            s.push_str("none.\n");
        } else {
            s.push_str(&format!("({})\n\n", items.len()));
            for i in items {
                s.push_str(&format!("- {i}\n"));
            }
        }
    };
    let unformal: Vec<String> = doc
        .claims
        .iter()
        .filter(|c| !formalized.contains(c.id.as_str()))
        .map(|c| format!("`{}` — {}", c.id, if c.statement().is_empty() { "(no statement)" } else { c.statement() }))
        .collect();
    bullets("Claims with no formal block", unformal, &mut s);
    let vacuous: Vec<String> = doc
        .claims
        .iter()
        .filter(|c| formalized.contains(c.id.as_str()) && status(doc, ledger, &c.id) == Status::Vacuous)
        .map(|c| {
            let n = ledger.invariants.get(&c.id).map(|r| r.mutants.len()).unwrap_or(0);
            if n > 0 {
                format!("`{}` — ⚠ Vacuous: caught none of {n} mutants; it does not count toward coverage", c.id)
            } else {
                format!("`{}` — ⚠ Vacuous: caught no mutant; it does not count toward coverage", c.id)
            }
        })
        .collect();
    bullets("Formal blocks that caught no mutant (Vacuous)", vacuous, &mut s);
    if ledger.mutants_known {
        let untried: Vec<String> = doc
            .claims
            .iter()
            .filter(|c| {
                formalized.contains(c.id.as_str())
                    && status(doc, ledger, &c.id) != Status::Vacuous
                    && ledger.invariants.get(&c.id).map(|r| r.mutants.is_empty()).unwrap_or(true)
            })
            .map(|c| format!("`{}` — run `invariant_mutate` before it counts", c.id))
            .collect();
        bullets("Formal blocks with no recorded mutant", untried, &mut s);
    }
    let claimed: BTreeSet<&str> = doc.claims.iter().map(|c| c.id.as_str()).collect();
    let orphans: Vec<String> =
        formalized.iter().filter(|id| !claimed.contains(*id)).map(|id| format!("`{id}` — formal block with no §6 claim")).collect();
    bullets("Formal blocks without a claim", orphans, &mut s);
    let covered: BTreeSet<String> = doc.claims.iter().flat_map(|c| c.actions().into_iter().chain(c.covers())).collect();
    let bare: Vec<String> =
        doc.actions.iter().filter(|a| !covered.contains(*a)).map(|a| format!("`{a}` — no invariant names this action")).collect();
    bullets("Actions without an invariant", bare, &mut s);
    s
}

fn history(doc: &SpecDoc, ledger: &Ledger) -> String {
    let mut s = format!("{}\n\n{GENERATED_NOTE}\n\n", SpecSection::History.heading());
    let mut rows = Vec::new();
    for c in &doc.claims {
        if let Some((old, why)) = c.supersedes() {
            let was =
                ledger.invariants.get(&old).and_then(|r| r.checked.as_ref()).map(|(_, v, _)| verdict_word(v)).unwrap_or("never checked");
            let stmt = doc
                .claim(&old)
                .map(|o| o.statement().to_string())
                .or_else(|| ledger.invariants.get(&old).and_then(|r| r.registrations.last()).map(|r| r.2.clone()))
                .unwrap_or_default();
            let why = if why.is_empty() { "no reason given".to_string() } else { why };
            rows.push(format!("- `{old}` superseded by `{}` — {why}. Old statement: “{stmt}”; last verdict: {was}.", c.id));
        }
    }
    for (id, r) in &ledger.invariants {
        let statements: Vec<&(EntryId, FormalKind, String, Vec<String>)> = r.registrations.iter().collect();
        for w in statements.windows(2) {
            if w[0].2 != w[1].2 {
                rows.push(format!(
                    "- `{id}` goalpost moved at entry {}: “{}” → “{}” (a changed statement should be a new id with `supersedes`).",
                    w[1].0.0, w[0].2, w[1].2
                ));
            }
        }
        let superseded = doc.claims.iter().any(|c| c.supersedes().map(|(o, _)| o == *id).unwrap_or(false));
        if doc.claim(id).is_none() && !superseded {
            let was = r.checked.as_ref().map(|(_, v, _)| verdict_word(v)).unwrap_or("never checked");
            rows.push(format!("- `{id}` is in the log but no longer in §6, with no superseding entry; last verdict: {was}."));
        }
    }
    if rows.is_empty() {
        s.push_str("No invariant has been superseded or withdrawn.\n");
    } else {
        for r in rows {
            s.push_str(&r);
            s.push('\n');
        }
    }
    s
}

fn verdict_word(v: &Verdict) -> &'static str {
    match v {
        Verdict::Pass => "Pass",
        Verdict::Fail { .. } => "Fail",
        Verdict::Unknown { .. } => "Unknown",
        Verdict::Stale => "Stale",
        Verdict::Vacuous => "Vacuous",
    }
}
