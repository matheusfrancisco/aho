#!/usr/bin/env python3
"""Regenerates crates/seams/aho-llm/models.tsv: display name, reasoning support and list price
of the models behind aho's own llm routes, from oh-my-pi's model catalog (MIT).

    python3 scripts/models.py <path to @oh-my-pi/pi-catalog/src/models.json> <catalog version>

One row per (route, model id), sorted, tab-separated:
    route  id  name  reasoning  input  output  cache_read  cache_write
Prices are USD per million tokens (the catalog's base tier; long-context surcharges are not
modelled). Routes without a catalog entry (ollama, radius, scripted, custom `provider.<name>`
rows) have no price, and the TUI shows their token counts instead. The catalog's context windows
are not copied: they assume request options (e.g. Anthropic's 1M beta) aho does not send, and
compaction reads `model.context_window`.
"""

import json
import sys
from pathlib import Path

# aho route -> catalog provider
ROUTES = {
    "anthropic": "anthropic",
    "github-copilot": "github-copilot",
    "kimi-coding": "kimi-code",
    "meta": "meta",
    "openai": "openai",
    "openai-codex": "openai-codex",
    "openrouter": "openrouter",
    "xai": "xai",
}

OUT = Path(__file__).resolve().parent.parent / "crates" / "seams" / "aho-llm" / "models.tsv"


def clean(s) -> str:
    return " ".join(str(s).replace("\t", " ").split())


def num(v) -> str:
    f = float(v or 0)
    return str(int(f)) if f.is_integer() else repr(f)


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__.strip(), file=sys.stderr)
        return 2
    catalog = json.loads(Path(sys.argv[1]).read_text())
    rows = []
    for route, provider in sorted(ROUTES.items()):
        models = catalog.get(provider)
        if not models:
            print(f"catalog has no provider {provider!r} (route {route})", file=sys.stderr)
            return 1
        for mid, m in models.items():
            cost = m.get("cost")
            if not mid or "\t" in mid or not cost:
                continue
            values = [float(cost.get(k) or 0) for k in ("input", "output", "cacheRead", "cacheWrite")]
            if any(v < 0 for v in values):
                continue  # a sentinel: the price is decided per request (openrouter/auto)
            prices = tuple(num(v) for v in values)
            rows.append((route, mid, clean(m.get("name") or mid), str(bool(m.get("reasoning"))).lower()) + prices)
    rows.sort()
    head = [
        f"# generated by scripts/models.py from @oh-my-pi/pi-catalog {sys.argv[2]} (MIT,",
        "# Copyright (c) 2025-2026 Can Bölük, Copyright (c) 2026 Stencil Labs, Inc.); do not edit.",
        "# route\tid\tname\treasoning\tinput\toutput\tcache_read\tcache_write (USD per million tokens)",
    ]
    OUT.write_text("\n".join(head + ["\t".join(r) for r in rows]) + "\n")
    print(f"{OUT}: {len(rows)} models")
    return 0


if __name__ == "__main__":
    sys.exit(main())
